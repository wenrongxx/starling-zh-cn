#[inline]
pub fn tr(text: &str) -> &str {
    match ZH.binary_search_by(|(en, _)| (*en).cmp(text)) {
        Ok(i) => ZH[i].1,
        Err(_) => match tr_extra(text) {
            Some(zh) => zh,
            None => {
                report_missing(text);
                text
            }
        },
    }
}

/// 每个未翻译的字符串只报告一次，写进日志（adb logcat 可读）。
fn report_missing(text: &str) {
    use std::sync::Mutex;
    static SEEN: Mutex<Option<std::collections::HashSet<String>>> = Mutex::new(None);
    let mut guard = SEEN.lock().unwrap();
    let set = guard.get_or_insert_with(Default::default);
    if text.len() >= 2 && set.insert(text.to_owned()) {
        log::warn!("i18n_missing: {text:?}");
    }
}

/// 只在需要自己持有字符串时使用（如 fit_text 的返回值）。
#[inline]
fn lookup(text: &str) -> Option<&'static str> {
    match ZH.binary_search_by(|(en, _)| (*en).cmp(text)) {
        Ok(i) => Some(ZH[i].1),
        Err(_) => tr_extra(text),
    }
}

/// 带模式兜底的翻译：能返回拼接结果，所以返回 String。
pub fn tr_owned(text: &str) -> String {
    if let Some(z) = lookup(text) {
        return z.to_string();
    }
    // “All (3)” → “全部 (3)”：只译前缀，保留计数。
    if let Some(pos) = text.rfind(" (") {
        if text.ends_with(')') {
            let (head, tail) = text.split_at(pos);
            let num = &tail[2..tail.len() - 1];
            if !num.is_empty() && num.chars().all(|c| c.is_ascii_digit() || c == ',') {
                if let Some(h) = lookup(head) {
                    return format!("{h} ({num})");
                }
            }
        }
    }
    // “a · b · c”：逐段翻译再拼回。
    if text.contains(" · ") {
        let joined = text.split(" · ").map(tr_owned).collect::<Vec<_>>().join(" · ");
        if joined != text {
            return joined;
        }
    }
    // 子串兜底：只在**整词**边界替换，避免把 Gameplay 切成「游戏play」。
    {
        let mut s = text.to_owned();
        let mut changed = false;
        let wordish =
            |c: char| c.is_ascii_alphanumeric() || c == '_' || c == '-' || c == '.' || c == '/';
        for (en, zh) in ZH_EXTRA.iter() {
            if en.len() < 3 {
                continue;
            }
            let mut out = String::new();
            let mut rest = s.as_str();
            while let Some(pos) = rest.find(en) {
                let before_ok = rest[..pos].chars().next_back().map_or(true, |c| !wordish(c));
                let after = &rest[pos + en.len()..];
                let after_ok = after.chars().next().map_or(true, |c| !wordish(c));
                if before_ok && after_ok {
                    out.push_str(&rest[..pos]);
                    out.push_str(zh);
                    rest = after;
                    changed = true;
                } else {
                    out.push_str(&rest[..pos + en.len()]);
                    rest = after;
                }
            }
            out.push_str(rest);
            s = out;
        }
        if changed {
            return s;
        }
    }
    report_missing(text);
    text.to_owned()
}

